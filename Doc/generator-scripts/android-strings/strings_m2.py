def android_escape(text: str) -> str:
    text = escape(text)  # & < >
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if text.startswith("@") or text.startswith("?"):
        text = "\\" + text
    return text


def write(path: Path, column: int, header: str) -> None:
    keys = [row[0] for row in S]
    assert len(keys) == len(set(keys)), "duplicate keys"
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {header} -->", "<resources>"]
    for row in S:
        lines.append(f'    <string name="{row[0]}">{android_escape(row[column])}</string>')
    lines.append("</resources>")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


